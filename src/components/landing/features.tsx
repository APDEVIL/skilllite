function FeatureCard({
  feature,
  index,
}: {
  feature: (typeof FEATURES)[0];
  index: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry?.isIntersecting) {
          setVisible(true);
          observer.disconnect();
        }
      },
      { threshold: 0.15 },
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  const Icon = feature.icon;

  return (
    <div
      ref={ref}
      className={cn(
        "group relative rounded-2xl border border-white/8 bg-gradient-to-br from-white/5 to-white/[0.02] p-6 overflow-hidden transition-all duration-700 hover:border-white/15 hover:bg-white/[0.07] cursor-default",
        visible ? "opacity-100 translate-y-0" : "opacity-0 translate-y-8",
      )}
      style={{ transitionDelay: `${index * 80}ms` }}
    >
      {/* Hover glow effect */}
      <div
        className={cn(
          "absolute inset-0 opacity-0 group-hover:opacity-100 transition-opacity duration-500 rounded-2xl blur-2xl",
          feature.glow === "blue" && "bg-blue-600/5",
          feature.glow === "violet" && "bg-violet-600/5",
          feature.glow === "pink" && "bg-pink-600/5",
          feature.glow === "emerald" && "bg-emerald-600/5",
          feature.glow === "amber" && "bg-amber-600/5",
          feature.glow === "indigo" && "bg-indigo-600/5",
        )}
      />

      {/* Top row: icon + step tag */}
      <div className="flex items-start justify-between mb-4">
        <div
          className={cn(
            "w-10 h-10 rounded-xl bg-gradient-to-br flex items-center justify-center shadow-lg",
            feature.color,
          )}
        >
          <Icon className="w-5 h-5 text-white" />
        </div>
        <span className="text-[10px] font-semibold tracking-widest text-slate-600 uppercase pt-1">
          {feature.tag}
        </span>
      </div>

      {/* Content */}
      <h3 className="text-base font-bold text-white mb-2 group-hover:text-white transition-colors">
        {feature.title}
      </h3>
      <p className="text-sm text-slate-500 leading-relaxed group-hover:text-slate-400 transition-colors">
        {feature.description}
      </p>

      {/* Bottom gradient line */}
      <div
        className={cn(
          "absolute bottom-0 left-0 right-0 h-px bg-gradient-to-r opacity-0 group-hover:opacity-100 transition-opacity duration-500",
          `from-transparent via-${feature.glow}-500/50 to-transparent`,
        )}
      />
    </div>
  );
}

